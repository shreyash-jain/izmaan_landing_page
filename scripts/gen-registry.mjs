// Emits lib/posts-registry.generated.ts — a plain, dependency-free copy of the
// blog registry that code running *without a filesystem* can import.
//
// Why this exists: lib/posts.ts reads content/blog/*.md with node:fs, which is
// fine at build time but impossible inside a Cloudflare Pages Function. The
// analytics endpoint needs post titles and categories to join GA page paths
// back to real content, so the registry is baked into a module at build time.
//
// Runs as part of `npm run build`. The output is committed so a deploy that
// skips the prebuild step still has a valid (if slightly stale) registry.

import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import matter from "gray-matter";

const ROOT = process.cwd();
const POSTS_DIR = path.join(ROOT, "content", "blog");
const OUT = path.join(ROOT, "lib", "posts-registry.generated.ts");

if (!existsSync(POSTS_DIR)) {
  console.error(`[gen-registry] ${POSTS_DIR} not found`);
  process.exit(1);
}

const posts = readdirSync(POSTS_DIR)
  .filter((f) => f.endsWith(".md") || f.endsWith(".mdx"))
  .map((file) => {
    const slug = file.replace(/\.mdx?$/, "");
    const { data } = matter(readFileSync(path.join(POSTS_DIR, file), "utf8"));
    return {
      slug,
      path: `/journal/${slug}`,
      title: data.title ?? slug,
      category: data.category ?? "Field Notes",
      date: data.date ? String(data.date).slice(0, 10) : "",
    };
  })
  .sort((a, b) => (a.date < b.date ? 1 : -1));

// Non-post pages the dashboard should still be able to name.
const staticPages = [
  { slug: "home", path: "/", title: "Home", category: "Page", date: "" },
  { slug: "journal", path: "/journal", title: "Journal", category: "Page", date: "" },
];

const body = `// AUTO-GENERATED by scripts/gen-registry.mjs — do not edit by hand.
// Regenerate with \`npm run gen:registry\` (also runs as part of \`npm run build\`).
//
// A filesystem-free mirror of the blog registry, so the Cloudflare Pages
// Function at /api/analytics can join GA page paths to real titles.

export type RegistryEntry = {
  slug: string;
  path: string;
  title: string;
  category: string;
  date: string;
};

export const POST_REGISTRY: RegistryEntry[] = ${JSON.stringify(posts, null, 2)};

export const PAGE_REGISTRY: RegistryEntry[] = ${JSON.stringify(staticPages, null, 2)};

/** Every known path, posts first. */
export const ALL_ENTRIES: RegistryEntry[] = [...POST_REGISTRY, ...PAGE_REGISTRY];

/** Look up an entry by GA pagePath, tolerating trailing slashes and query strings. */
export function lookupPath(pagePath: string): RegistryEntry | undefined {
  const clean = pagePath.split("?")[0].replace(/\\/$/, "") || "/";
  return ALL_ENTRIES.find((e) => e.path === clean);
}
`;

writeFileSync(OUT, body, "utf8");
console.log(
  `[gen-registry] wrote ${path.relative(ROOT, OUT)} — ${posts.length} posts, ${staticPages.length} pages`
);
